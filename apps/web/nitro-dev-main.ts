/**
 * Dev-only nitro plugin (registered from vite.config.ts `nitro.plugins`).
 *
 * Nitro's public-assets reader (`#nitro/virtual/public-assets-node`)
 * resolves each asset path — stored relative to `output.serverDir` —
 * against `dirname(globalThis.__nitro_main__)`. The built server bundle
 * sets that global in its entry prepend, but under `vite dev` the nitro
 * environment is never bundled, so nothing sets it: the first import to
 * claim the global is the eve `.output/server/index.mjs` mount in
 * agent/runtime.ts, and every `dist/client/*` asset path then resolves
 * one level too high (`apps/dist/client/index.html`) -> ENOENT 500s.
 * The bug stays hidden until `pnpm build` populates dist/, because the
 * dev asset manifest is generated by globbing output.publicDir.
 *
 * This plugin runs inside the nitro dev environment at app init —
 * before any request is served — and anchors the global at the nitro
 * dev serverDir (`node_modules/.nitro/dev`, the nitro-dev preset's
 * output.serverDir) so `../../..`-relative asset paths land back on
 * `apps/web/dist/client`. The `if` guard keeps the built/preview
 * bundle's own value untouched (its entry prepend runs first).
 */
import { join } from "node:path";
import { pathToFileURL } from "node:url";

declare global {
  // eslint-disable-next-line no-var
  var __nitro_main__: string | undefined;
}

export default function tarimaDevNitroMain() {
  if (globalThis.__nitro_main__) return;
  globalThis.__nitro_main__ = pathToFileURL(
    join(process.cwd(), "node_modules", ".nitro", "dev", "index.mjs"),
  ).href;
}
